CREATE TABLE competition_seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id BIGINT NOT NULL REFERENCES competitions (id) ON DELETE RESTRICT,
    season_id BIGINT NOT NULL REFERENCES seasons (id) ON DELETE RESTRICT,
    CONSTRAINT uq_competition_seasons_pair UNIQUE (competition_id, season_id)
);

INSERT INTO competition_seasons (competition_id, season_id)
SELECT DISTINCT old.competition_id, canonical.id
FROM seasons old
JOIN LATERAL (
    SELECT MIN(id) AS id FROM seasons WHERE name = old.name
) canonical ON TRUE;

DELETE FROM seasons duplicate
USING seasons canonical
WHERE duplicate.name = canonical.name AND duplicate.id > canonical.id;

ALTER TABLE seasons DROP CONSTRAINT uq_seasons_competition_name;
ALTER TABLE seasons DROP COLUMN competition_id;
ALTER TABLE seasons ADD CONSTRAINT uq_seasons_name UNIQUE (name);

CREATE INDEX idx_competition_seasons_season_id ON competition_seasons (season_id);

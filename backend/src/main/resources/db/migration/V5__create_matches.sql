CREATE TABLE matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_season_id BIGINT NOT NULL REFERENCES competition_seasons(id) ON DELETE RESTRICT,
    home_team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    away_team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    kickoff_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('SCHEDULED','LIVE','FINISHED','POSTPONED','CANCELLED')),
    home_score INTEGER CHECK (home_score >= 0),
    away_score INTEGER CHECK (away_score >= 0),
    round TEXT,
    CONSTRAINT ck_matches_different_teams CHECK (home_team_id <> away_team_id),
    CONSTRAINT ck_matches_score_pair CHECK ((home_score IS NULL) = (away_score IS NULL)),
    CONSTRAINT ck_matches_status_scores CHECK (
        (status IN ('SCHEDULED','POSTPONED','CANCELLED') AND home_score IS NULL AND away_score IS NULL)
        OR status = 'LIVE'
        OR (status = 'FINISHED' AND home_score IS NOT NULL AND away_score IS NOT NULL)
    )
);
CREATE INDEX idx_matches_competition_kickoff ON matches(competition_season_id, kickoff_time DESC, id DESC);
CREATE INDEX idx_matches_home_history ON matches(home_team_id, status, kickoff_time DESC, id DESC);
CREATE INDEX idx_matches_away_history ON matches(away_team_id, status, kickoff_time DESC, id DESC);
CREATE INDEX idx_matches_kickoff ON matches(kickoff_time DESC, id DESC);
CREATE INDEX idx_matches_scheduled_due ON matches(kickoff_time) WHERE status = 'SCHEDULED';

CREATE TABLE match_statistics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL UNIQUE REFERENCES matches(id) ON DELETE RESTRICT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    home_big_chances INTEGER CHECK (home_big_chances >= 0),
    home_clearances INTEGER CHECK (home_clearances >= 0),
    home_corners INTEGER CHECK (home_corners >= 0),
    home_crosses INTEGER CHECK (home_crosses >= 0),
    home_interceptions INTEGER CHECK (home_interceptions >= 0),
    home_key_passes INTEGER CHECK (home_key_passes >= 0),
    home_long_passes INTEGER CHECK (home_long_passes >= 0),
    home_pass_accuracy INTEGER CHECK (home_pass_accuracy BETWEEN 0 AND 100),
    home_passes_final_third INTEGER CHECK (home_passes_final_third >= 0),
    home_possession INTEGER CHECK (home_possession BETWEEN 0 AND 100),
    home_red_cards INTEGER CHECK (home_red_cards >= 0),
    home_shots INTEGER CHECK (home_shots >= 0),
    home_shots_on_target INTEGER CHECK (home_shots_on_target >= 0),
    home_touches_in_box INTEGER CHECK (home_touches_in_box >= 0),
    home_xg NUMERIC(10,2) CHECK (home_xg >= 0),
    home_yellow_cards INTEGER CHECK (home_yellow_cards >= 0),
    away_big_chances INTEGER CHECK (away_big_chances >= 0),
    away_clearances INTEGER CHECK (away_clearances >= 0),
    away_corners INTEGER CHECK (away_corners >= 0),
    away_crosses INTEGER CHECK (away_crosses >= 0),
    away_interceptions INTEGER CHECK (away_interceptions >= 0),
    away_key_passes INTEGER CHECK (away_key_passes >= 0),
    away_long_passes INTEGER CHECK (away_long_passes >= 0),
    away_pass_accuracy INTEGER CHECK (away_pass_accuracy BETWEEN 0 AND 100),
    away_passes_final_third INTEGER CHECK (away_passes_final_third >= 0),
    away_possession INTEGER CHECK (away_possession BETWEEN 0 AND 100),
    away_red_cards INTEGER CHECK (away_red_cards >= 0),
    away_shots INTEGER CHECK (away_shots >= 0),
    away_shots_on_target INTEGER CHECK (away_shots_on_target >= 0),
    away_touches_in_box INTEGER CHECK (away_touches_in_box >= 0),
    away_xg NUMERIC(10,2) CHECK (away_xg >= 0),
    away_yellow_cards INTEGER CHECK (away_yellow_cards >= 0)
);

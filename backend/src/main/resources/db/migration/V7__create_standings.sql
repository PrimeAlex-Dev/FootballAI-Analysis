CREATE TABLE standings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_season_id BIGINT NOT NULL UNIQUE REFERENCES competition_seasons(id) ON DELETE RESTRICT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE standing_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standing_id BIGINT NOT NULL REFERENCES standings(id) ON DELETE CASCADE,
    table_index INTEGER NOT NULL CHECK (table_index >= 0),
    row_index INTEGER NOT NULL CHECK (row_index >= 0),
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    rank INTEGER NOT NULL CHECK (rank > 0),
    matches_played INTEGER NOT NULL CHECK (matches_played >= 0),
    wins INTEGER NOT NULL CHECK (wins >= 0),
    draws INTEGER NOT NULL CHECK (draws >= 0),
    losses INTEGER NOT NULL CHECK (losses >= 0),
    goals_for INTEGER NOT NULL CHECK (goals_for >= 0),
    goals_against INTEGER NOT NULL CHECK (goals_against >= 0),
    goal_difference INTEGER NOT NULL,
    points INTEGER NOT NULL,
    UNIQUE (standing_id, table_index, row_index),
    UNIQUE (standing_id, table_index, team_id)
);
CREATE INDEX idx_standing_rows_team ON standing_rows(team_id);

CREATE TABLE competitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(btrim(name)) > 0 AND name = btrim(name)),
    type VARCHAR(20) NOT NULL CHECK (type IN ('LEAGUE', 'CUP')),
    logo TEXT
);

CREATE TABLE seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id BIGINT NOT NULL REFERENCES competitions (id) ON DELETE RESTRICT,
    name TEXT NOT NULL CHECK (name ~ '^[0-9]{4}(/[0-9]{4})?$'),
    CONSTRAINT uq_seasons_competition_name UNIQUE (competition_id, name)
);

